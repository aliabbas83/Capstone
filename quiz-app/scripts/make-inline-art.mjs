// Puts the demo flags and the pool water picture INSIDE the app's code, as data URIs.
//
// Why: in Expo Go a "bundled" image file is still downloaded from the dev server the first
// time it is shown. If the phone cannot reach the computer at that moment, the picture fails
// ("ما قدرنا نحمّل الصورة") even though the demo is meant to work with no connection.
// Pictures written into the code need no download on any platform.
//
// Run: node scripts/make-inline-art.mjs   (re-run after changing a file in assets/flags or assets/pool)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataUri = (file, type) => `data:${type};base64,${readFileSync(join(ROOT, file)).toString('base64')}`;

const FLAGS = ['kw', 'jp', 'ca', 'br', 'kr', 'gr', 'np'];
const flags = FLAGS.map((code) => `  ${code}:\n    '${dataUri(`assets/flags/${code}.png`, 'image/png')}',`).join('\n');
writeFileSync(
  join(ROOT, 'src/game/demo-flags.ts'),
  `// GENERATED by scripts/make-inline-art.mjs from assets/flags/*.png. Do not edit by hand.
// The demo's flag pictures (flagcdn.com, public domain) as data URIs, so they need no download.
export const DEMO_FLAGS = {
${flags}
} as const;
`,
);

writeFileSync(
  join(ROOT, 'src/components/pool-water.ts'),
  `// GENERATED by scripts/make-inline-art.mjs from assets/pool/water.jpg. Do not edit by hand.
// Pool water seen from above (AI-generated artwork, 960 × 540) as a data URI, so it needs no download.
export const POOL_WATER =
  '${dataUri('assets/pool/water.jpg', 'image/jpeg')}';
`,
);
console.log('wrote src/game/demo-flags.ts and src/components/pool-water.ts');
