// Turns the real question bank (CSV files in supabase/questions/, ignored by git) into
// supabase/questions/load.sql, ready to paste into the Supabase SQL Editor.
//
//   node supabase/scripts/questions-to-sql.mjs                  check + write load.sql
//   node supabase/scripts/questions-to-sql.mjs --retire-samples also switch off the public sample questions
//
// CSV columns: category,points,question,answer   (UTF-8; Excel/Google Sheets "CSV UTF-8" is fine)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'questions');
const OUT = join(DIR, 'load.sql');
const retire = process.argv.includes('--retire-samples');

/** Minimal RFC 4180 CSV parser: quotes, "" escapes, commas and new lines inside quotes. */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  let line = 1;
  let rowLine = 1;
  text = text.replace(/^﻿/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') (field += '"'), i++;
      else if (c === '"') quoted = false;
      else {
        if (c === '\n') line++;
        field += c;
      }
    } else if (c === '"') quoted = true;
    else if (c === ',') row.push(field), (field = '');
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      rows.push({ line: rowLine, cells: row });
      row = [];
      field = '';
      rowLine = ++line;
    } else field += c;
  }
  if (field !== '' || row.length) row.push(field), rows.push({ line: rowLine, cells: row });
  return rows.filter((r) => r.cells.some((x) => x.trim() !== ''));
}

const clean = (s) => s.replace(/\s+/g, ' ').trim();
const sql = (s) => `'${s.replace(/'/g, "''")}'`;

function main() {
  const files = readdirSync(DIR).filter((f) => f.toLowerCase().endsWith('.csv') && f !== 'template.csv');
  if (files.length === 0) {
    console.error(`No CSV files in ${DIR}. Copy template.csv to e.g. bank.csv and fill it in.`);
    process.exit(1);
  }

  const errors = [];
  const seen = new Map();
  const items = [];
  let examples = 0;

  for (const file of files) {
    const rows = parseCsv(readFileSync(join(DIR, file), 'utf8'));
    const header = rows.shift()?.cells.map((h) => clean(h).toLowerCase()).join(',');
    if (header !== 'category,points,question,answer') {
      errors.push(`${file}: first row must be: category,points,question,answer`);
      continue;
    }
    for (const { line, cells } of rows) {
      const at = `${file}:${line}`;
      if (cells.length !== 4) {
        errors.push(`${at}: needs 4 columns, found ${cells.length} (put text with commas in "quotes")`);
        continue;
      }
      const [category, points, question, answer] = cells.map(clean);
      if (question.startsWith('مثال')) {
        examples++;
        continue;
      }
      if (!/^[a-z_]{2,30}$/.test(category)) errors.push(`${at}: category "${category}" is not a category id (e.g. geo)`);
      if (!['2', '3', '4', '5'].includes(points)) errors.push(`${at}: points must be 2, 3, 4 or 5 (found "${points}")`);
      if (question.length < 5 || question.length > 300) errors.push(`${at}: question must be 5–300 characters`);
      if (answer.length < 1 || answer.length > 120) errors.push(`${at}: answer must be 1–120 characters`);
      if (seen.has(question)) errors.push(`${at}: same question as ${seen.get(question)}`);
      seen.set(question, at);
      items.push({ category, points, question, answer });
    }
  }

  if (examples) console.warn(`Skipped ${examples} example row(s) starting with "مثال".`);
  if (errors.length) {
    console.error(`Fix these ${errors.length} problem(s), then run again:\n- ${errors.join('\n- ')}`);
    process.exit(1);
  }
  if (items.length === 0) {
    console.error('No questions found (only example rows?).');
    process.exit(1);
  }

  const categories = [...new Set(items.map((q) => q.category))];
  const out = [
    `-- Generated by supabase/scripts/questions-to-sql.mjs on ${new Date().toISOString()}`,
    `-- ${items.length} questions from: ${files.join(', ')}. NEVER commit this file.`,
    'begin;',
    '',
    'do $$',
    'declare missing text;',
    'begin',
    `  select string_agg(c, ', ') into missing from unnest(array[${categories.map(sql).join(', ')}]) c`,
    '   where not exists (select 1 from public.categories where id = c);',
    "  if missing is not null then raise exception 'Unknown categories: %', missing; end if;",
    'end $$;',
    '',
  ];
  if (retire) {
    out.push('-- Switch off the sample questions that are public on GitHub.', 'update public.questions set active = false where is_sample;', '');
  }
  out.push(
    'insert into public.questions (category_id, points, question, answer) values',
    items.map((q) => `  (${sql(q.category)}, ${q.points}, ${sql(q.question)}, ${sql(q.answer)})`).join(',\n'),
    'on conflict (question, image_path) do update',
    '  set category_id = excluded.category_id, points = excluded.points, answer = excluded.answer,',
    '      active = true, is_sample = false;',
    '',
    '-- How many questions are ready per category and points:',
    'select category_id, points, count(*) as ready from public.questions where active group by 1, 2 order by 1, 2;',
    '',
    'commit;',
    '',
  );
  writeFileSync(OUT, out.join('\n'));

  const per = {};
  for (const q of items) per[`${q.category} ${q.points}`] = (per[`${q.category} ${q.points}`] ?? 0) + 1;
  console.log(`OK: ${items.length} questions → ${OUT}${retire ? ' (sample questions will be switched off)' : ''}`);
  console.table(per);
  console.log('Next: Supabase dashboard → SQL Editor → paste load.sql → Run.');
}

main();
